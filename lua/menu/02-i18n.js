  // fallback.
  function slsStrings() {
    var L = I18N[pickLang()];
    return (L && L.sls) || I18N.en.sls;
  }

  function autoFixStrings() {
    var L = I18N[pickLang()];
    return (L && L.autoFix) || I18N.en.autoFix;
  }

  function installReadinessStrings() {
    var L = I18N[pickLang()];
    return (L && L.installReadiness) || I18N.en.installReadiness;
  }

